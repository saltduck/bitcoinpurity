"""Generate depends/packages/sv2_crates.mk from src/sv2/Cargo.lock.

The depends package downloads every crates.io dependency of the embedded SV2
gateway by the checksum recorded in Cargo.lock, plus the pinned stratum
source archive, so that cargo can build offline (for example inside Guix).

Usage:
  contrib/devtools/gen-sv2-crates-mk.py          # rewrite the .mk file
  contrib/devtools/gen-sv2-crates-mk.py --check  # fail if it is out of date
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCK = ROOT / "src" / "sv2" / "Cargo.lock"
OUTPUT = ROOT / "depends" / "packages" / "sv2_crates.mk"

STRATUM_URL = "https://github.com/stratum-mining/stratum"
# sha256 of https://codeload.github.com/stratum-mining/stratum/tar.gz/<rev>.
# Update together with the rev in src/sv2/Cargo.toml.
STRATUM_ARCHIVES = {
    "d1d30f3e755b0a5108633e1be7012034a8caaecd":
        "4045063ac279a261709f4ed861608d2ec618c0313c6861d8d114cfb5c4524642",
}


def parse_lock(text):
    packages = []
    for block in text.split("[[package]]")[1:]:
        fields = dict(re.findall(r'^(\w+) = "([^"]*)"', block, re.M))
        packages.append(fields)
    return packages


def render(packages):
    crates = []
    revs = set()
    for p in packages:
        source = p.get("source", "")
        if source == "registry+https://github.com/rust-lang/crates.io-index":
            if not re.fullmatch(r"[0-9a-f]{64}", p.get("checksum", "")):
                raise SystemExit(f"missing checksum for {p['name']} {p['version']}")
            crates.append((p["name"], p["version"], p["checksum"]))
        elif source.startswith("git+" + STRATUM_URL + "?rev="):
            revs.add(source.split("#", 1)[1])
        elif source:
            raise SystemExit(f"unsupported source for {p['name']}: {source}")
    if len(revs) != 1:
        raise SystemExit(f"expected exactly one stratum revision, found {sorted(revs)}")
    rev = revs.pop()
    if rev not in STRATUM_ARCHIVES:
        raise SystemExit(f"add the sha256 of the stratum archive for {rev} to {Path(__file__).name}")
    crates.sort()

    out = []
    out.append("# Generated by contrib/devtools/gen-sv2-crates-mk.py from src/sv2/Cargo.lock.")
    out.append("# Do not edit by hand; rerun the script after changing Cargo.lock.")
    out.append("package=sv2_crates")
    out.append(f"$(package)_version={rev[:12]}")
    out.append(f"$(package)_stratum_rev={rev}")
    out.append("$(package)_download_path=https://codeload.github.com/stratum-mining/stratum/tar.gz")
    out.append("$(package)_download_file=$($(package)_stratum_rev)")
    out.append("$(package)_file_name=stratum-$($(package)_stratum_rev).tar.gz")
    out.append(f"$(package)_sha256_hash={STRATUM_ARCHIVES[rev]}")
    out.append("$(package)_crates_path=https://static.crates.io/crates")
    out.append("")
    out.append("# name version sha256")
    out.append("$(package)_crates= \\")
    for name, version, checksum in crates:
        out.append(f"  {name}:{version}:{checksum} \\")
    out.append("")
    out.append("$(package)_crate_name=$(word 1,$(subst :, ,$(1)))")
    out.append("$(package)_crate_version=$(word 2,$(subst :, ,$(1)))")
    out.append("$(package)_crate_hash=$(word 3,$(subst :, ,$(1)))")
    out.append("$(package)_crate_file=crate-$(call $(package)_crate_name,$(1))-$(call $(package)_crate_version,$(1)).crate")
    out.append("$(package)_extra_sources=$(foreach c,$($(package)_crates),$(call $(package)_crate_file,$(c)))")
    out.append("")
    out.append("define $(package)_fetch_cmds")
    out.append("$(call fetch_file,$(package),$($(package)_download_path),$($(package)_download_file),$($(package)_file_name),$($(package)_sha256_hash)) && \\")
    out.append("$(foreach c,$($(package)_crates),$(call fetch_file,$(package),$($(package)_crates_path)/$(call $(package)_crate_name,$(c)),$(call $(package)_crate_name,$(c))-$(call $(package)_crate_version,$(c)).crate,$(call $(package)_crate_file,$(c)),$(call $(package)_crate_hash,$(c))) && ) true")
    out.append("endef")
    out.append("")
    out.append("# Lay the crates out as a cargo directory source. An empty \"files\" map is")
    out.append("# accepted by cargo; the package checksum ties each crate to Cargo.lock.")
    out.append("define $(package)_extract_cmds")
    out.append("  mkdir -p $$($(package)_extract_dir) && \\")
    out.append("  echo \"$($(package)_sha256_hash)  $($(package)_source_dir)/$($(package)_file_name)\" > $$($(package)_extract_dir)/.$($(package)_file_name).hash && \\")
    out.append("  $(foreach c,$($(package)_crates),echo \"$(call $(package)_crate_hash,$(c))  $($(package)_source_dir)/$(call $(package)_crate_file,$(c))\" >> $$($(package)_extract_dir)/.$($(package)_file_name).hash && ) \\")
    out.append("  $(build_SHA256SUM) -c $$($(package)_extract_dir)/.$($(package)_file_name).hash && \\")
    out.append("  mkdir -p stratum vendor && \\")
    out.append("  $(build_TAR) --no-same-owner --strip-components=1 -C stratum -xf $($(package)_source_dir)/$($(package)_file_name) && \\")
    out.append("  $(foreach c,$($(package)_crates),mkdir -p vendor/$(call $(package)_crate_name,$(c))-$(call $(package)_crate_version,$(c)) && \\")
    out.append("    $(build_TAR) --no-same-owner --strip-components=1 -C vendor/$(call $(package)_crate_name,$(c))-$(call $(package)_crate_version,$(c)) -xzf $($(package)_source_dir)/$(call $(package)_crate_file,$(c)) && \\")
    out.append("    printf '{\"files\":{},\"package\":\"%s\"}' $(call $(package)_crate_hash,$(c)) > vendor/$(call $(package)_crate_name,$(c))-$(call $(package)_crate_version,$(c))/.cargo-checksum.json && ) true")
    out.append("endef")
    out.append("")
    out.append("define $(package)_stage_cmds")
    out.append("  mkdir -p $($(package)_staging_prefix_dir)/share/sv2-vendor && \\")
    out.append("  cp -R stratum vendor $($(package)_staging_prefix_dir)/share/sv2-vendor/")
    out.append("endef")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit non-zero if the file is out of date")
    args = parser.parse_args()
    text = render(parse_lock(LOCK.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
